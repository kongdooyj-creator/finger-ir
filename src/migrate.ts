import type { Env } from './types.ts';
import { PgDatabase } from './pg.ts';

/** Neon Postgres 스키마. 날짜·시각은 D1 과 같이 UTC ISO 문자열(TEXT)로 저장한다. */
const NOW_ISO = `to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`;

export const PG_SCHEMA: string[] = [
  `CREATE TABLE IF NOT EXISTS issues (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    summary TEXT DEFAULT '',
    severity TEXT NOT NULL DEFAULT '확인 필요',
    severity_code TEXT,
    severity_ai TEXT,
    severity_manual INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT '신규',
    suggested_action TEXT DEFAULT '',
    memo TEXT DEFAULT '',
    media TEXT DEFAULT '',
    legacy_id TEXT UNIQUE,
    created_at TEXT NOT NULL DEFAULT ${NOW_ISO},
    updated_at TEXT NOT NULL DEFAULT ${NOW_ISO}
  )`,
  `CREATE TABLE IF NOT EXISTS articles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL UNIQUE,
    url_norm TEXT NOT NULL,
    title TEXT NOT NULL,
    title_norm TEXT NOT NULL,
    summary TEXT DEFAULT '',
    publisher TEXT DEFAULT '',
    published_at TEXT,
    source TEXT DEFAULT '',
    tone TEXT NOT NULL DEFAULT '미분류',
    tone_by TEXT NOT NULL DEFAULT 'rule',
    severity TEXT NOT NULL DEFAULT '확인 필요',
    severity_code TEXT,
    confidence DOUBLE PRECISION DEFAULT 0,
    ai_summary TEXT DEFAULT '',
    evidence TEXT DEFAULT '',
    issue_id INTEGER REFERENCES issues(id),
    legacy_id TEXT UNIQUE,
    created_at TEXT NOT NULL DEFAULT ${NOW_ISO}
  )`,
  `CREATE INDEX IF NOT EXISTS idx_articles_url_norm ON articles(url_norm)`,
  `CREATE INDEX IF NOT EXISTS idx_articles_published ON articles(published_at DESC)`,
  `CREATE INDEX IF NOT EXISTS idx_articles_issue ON articles(issue_id)`,
  `CREATE TABLE IF NOT EXISTS fetch_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger TEXT NOT NULL DEFAULT 'cron',
    started_at TEXT NOT NULL,
    finished_at TEXT,
    candidates INTEGER DEFAULT 0,
    filtered INTEGER DEFAULT 0,
    duplicates INTEGER DEFAULT 0,
    imported INTEGER DEFAULT 0,
    classified INTEGER DEFAULT 0,
    feeds TEXT DEFAULT '[]',
    errors TEXT DEFAULT '[]'
  )`,
  `CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  )`,
  `CREATE TABLE IF NOT EXISTS media_contracts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher TEXT NOT NULL,
    relation TEXT DEFAULT '',
    status TEXT DEFAULT '',
    contact TEXT DEFAULT '',
    note TEXT DEFAULT ''
  )`,
];

// 외래키 때문에 issues → articles 순서로 옮긴다
const TABLES: { name: string; key: string; columns: string[] }[] = [
  { name: 'issues', key: 'id', columns: ['id', 'title', 'summary', 'severity', 'severity_code', 'severity_ai', 'severity_manual', 'status', 'suggested_action', 'memo', 'media', 'legacy_id', 'created_at', 'updated_at'] },
  { name: 'articles', key: 'id', columns: ['id', 'url', 'url_norm', 'title', 'title_norm', 'summary', 'publisher', 'published_at', 'source', 'tone', 'tone_by', 'severity', 'severity_code', 'confidence', 'ai_summary', 'evidence', 'issue_id', 'legacy_id', 'created_at'] },
  { name: 'fetch_runs', key: 'id', columns: ['id', 'trigger', 'started_at', 'finished_at', 'candidates', 'filtered', 'duplicates', 'imported', 'classified', 'feeds', 'errors'] },
  { name: 'settings', key: 'key', columns: ['key', 'value'] },
  { name: 'media_contracts', key: 'id', columns: ['id', 'publisher', 'relation', 'status', 'contact', 'note'] },
];

export async function ensurePgSchema(pg: PgDatabase): Promise<void> {
  for (const stmt of PG_SCHEMA) await pg.prepare(stmt).run();
}

async function counts(db: { prepare: (s: string) => { first: <T>() => Promise<T | null> } }): Promise<Record<string, number>> {
  const out: Record<string, number> = {};
  for (const t of TABLES) {
    const r = await db.prepare(`SELECT COUNT(*) AS n FROM ${t.name}`).first<{ n: number }>();
    out[t.name] = Number(r?.n ?? 0);
  }
  return out;
}

/**
 * D1 의 모든 행을 Neon 으로 복사한다. 여러 번 실행해도 안전하다(이미 있는 행은 건너뜀, settings 는 최신값으로 덮어씀).
 * 복사 후 각 테이블의 id 시퀀스를 최대값 다음으로 맞춘다.
 */
export async function copyD1ToPg(env: Env, d1: D1Database, pg: PgDatabase): Promise<Record<string, unknown>> {
  await ensurePgSchema(pg);
  const copied: Record<string, number> = {};
  for (const t of TABLES) {
    const { results } = await d1.prepare(`SELECT ${t.columns.join(', ')} FROM ${t.name} ORDER BY ${t.key}`).all<Record<string, unknown>>();
    copied[t.name] = 0;
    const conflict = t.name === 'settings'
      ? `ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value`
      : `ON CONFLICT (${t.key}) DO NOTHING`;
    for (let i = 0; i < results.length; i += 25) {
      const chunk = results.slice(i, i + 25);
      const rowSql = `(${t.columns.map(() => '?').join(', ')})`;
      const sql = `INSERT INTO ${t.name} (${t.columns.join(', ')}) VALUES ${chunk.map(() => rowSql).join(', ')} ${conflict}`;
      const params = chunk.flatMap((r) => t.columns.map((c) => r[c] ?? null));
      // RETURNING id 자동 부착을 피하려고 all() 로 실행
      const res = await pg.prepare(sql).bind(...params).all();
      copied[t.name] += Number(res.meta.changes ?? 0);
    }
    if (t.key === 'id') {
      await pg.prepare(`SELECT setval(pg_get_serial_sequence('${t.name}', 'id'), (SELECT COALESCE(MAX(id), 0) + 1 FROM ${t.name}), false)`).all();
    }
  }
  void env;
  return { copied, d1: await counts(d1 as never), pg: await counts(pg as never) };
}

export async function dbStatus(env: Env): Promise<Record<string, unknown>> {
  const usingPg = (env.DB as unknown as { dialect?: string }).dialect === 'pg';
  const out: Record<string, unknown> = { using: usingPg ? 'neon-postgres' : 'cloudflare-d1' };
  try { out.current = await counts(env.DB as never); } catch (e) { out.current_error = String(e); }
  if (usingPg && env.D1) { try { out.d1 = await counts(env.D1 as never); } catch (e) { out.d1_error = String(e); } }
  return out;
}
